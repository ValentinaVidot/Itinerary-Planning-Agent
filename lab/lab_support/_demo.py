class ScriptedClient:
    def __init__(self, messages=None):
        self.responses = iter(responses() if messages is None else messages)
        self.requests = []

    def complete(self, payload):
        # Copy: later history mutations must not alter captured request evidence.
        self.requests.append(json.loads(json.dumps(payload)))
        response = json.loads(json.dumps(next(self.responses)))
        for call in response["choices"][0]["message"].get("tool_calls", []):
            call["id"] = f"request-{len(self.requests)}-{call['id']}"
        return response


def run_demo(*, instructions=None, tools=None, agent_factory=None, runner=None):
    from ._runtime import LabSession, ROOT, interact
    from agent import create_agent
    if tools is None:
        tools = (agent_factory or create_agent)("offline-model").tools
    required = {"list_files", "read_file", "write_file", "update_plan", "search_local", "search_web"}
    missing = required - {tool.name for tool in tools}
    if missing:
        raise RunError("The scripted demo needs these tools restored in TOOLS: " + ", ".join(sorted(missing)))
    with tempfile.TemporaryDirectory(prefix="haid-demo-") as directory:
        root = Path(directory)
        shutil.copytree(ROOT / "data", root / "data")
        print("OFFLINE SCRIPTED DEMO — no model calls, no live searches, no measured token costs.")
        print("Uses the real tools in an isolated temporary workspace; your runtime/ is untouched.")
        ledger = Ledger(root / ".lab-state")
        agent = LabSession(Workspace(root), ScriptedClient(), ledger,
                           instructions=instructions, tools=tools,
                           agent_factory=agent_factory, runner=runner)
        print("Remaining lab budget: $1.00 (offline demo; no spending)")
        prompts = iter([INITIAL, FOLLOWUP, QUESTION, "/exit"])
        def supplied_input(prompt):
            value = next(prompts)
            print(prompt + value)
            return value
        try:
            interact(agent, supplied_input)
        finally:
            agent.connection.close()
        print("Demo finished. Temporary artifacts will now be removed.")
